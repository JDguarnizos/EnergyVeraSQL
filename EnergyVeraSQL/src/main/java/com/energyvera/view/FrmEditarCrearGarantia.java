    private void Guardar_jButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_Guardar_jButtonActionPerformed
        try {
                //Verificar que los campos no estén vacíos
            if (Codigo_jTextField.getText().isBlank()
                    || Motivo_jTextField.getText().isBlank()
                    || Fecha_jTextField3.getText().isBlank()
                    || FacturaVenta_jTextField.getText().isBlank()
                    ) {
                throw new NullPointerException("");
            }
                //Intentar conversión
                int cod_garantia = Integer.parseInt(Codigo_jTextField.getText());
                garantiaEditar.setIdGarantia(cod_garantia);
                Date fechaGarantia = Date.valueOf(Fecha_jTextField3.getText());
                garantiaEditar.setFecha(fechaGarantia);
                garantiaEditar.setMotivo(Motivo_jTextField.getText());
                int cod_FactVenta = Integer.parseInt(FacturaVenta_jTextField.getText());
                garantiaEditar.setIdFacturaV(cod_FactVenta);
            } catch (NumberFormatException n) {
                JOptionPane.showMessageDialog(this, "Gestión EnergyVera", "Asegurese que los campos númericos no contengan espacios o puntos", 2);
                return;
            } catch (NullPointerException e){
                JOptionPane.showMessageDialog(this, "Gestión EnergyVera", "Asegurese que los campos esten completos", 2);
                return;
            }
        //Detectar si estamos creando un nuevo cliente o editando uno actual para actualizarlo o guardarlo
        if (garantiaEditar != null) {
            serviceGarantia.actualizarGarantia(garantiaEditar);
            JOptionPane.showMessageDialog(this, "Gestión EnergyVera", "Garantía " + garantiaEditar.getIdGarantia()+ " editada exitosamente!", 2);
        } else {
            serviceGarantia.registrarGarantia(garantiaEditar);
            JOptionPane.showMessageDialog(this, "Gestión EnergyVera", "Garantía " + garantiaEditar.getIdGarantia()+ " añadida exitosamente!", 2);
        }
        FrmGarantias factForm = new FrmGarantias(serviceGarantia);
        factForm.setVisible(true);
        this.dispose();
    }//GEN-LAST:event_Guardar_jButtonActionPerformed


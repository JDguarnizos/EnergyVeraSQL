    public void inicializarVista() {
        if (garantiaEditar != null) {
            Titulo_JLabel.setText("Editar Factura");
            Codigo_jTextField.setText(String.valueOf(garantiaEditar.getIdGarantia()));
            Motivo_jTextField.setText(garantiaEditar.getMotivo());
            Fecha_jTextField3.setText(String.valueOf(garantiaEditar.getFecha()));
            FacturaVenta_jTextField.setText(String.valueOf(garantiaEditar.getIdFacturaV()));
            Guardar_jButton.setText("Guardar");
        }else{
            Titulo_JLabel.setText("Añadir Factura");
            Codigo_jTextField.setText("Número sin espacios ni letras");
            Motivo_jTextField.setText("");
            Fecha_jTextField3.setText("Día/Mes/Año");
            FacturaVenta_jTextField.setText("Número sin espacios ni letras");
            Guardar_jButton.setText("Añadir");
        }
    }


    private void Guardar_jButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_Guardar_jButtonActionPerformed
        try {
                //Verificar que los campos no estén vacíos
            if (Codigo_jTextField.getText().isBlank()
                    || Marca_jTextField.getText().isBlank()
                    || Precio_jTextField3.getText().isBlank()
                    || Stock_jTextField.getText().isBlank()
                    || Tipo_jTextField.getText().isBlank()
                    ) {
                throw new NullPointerException("");
            }
                //Intentar conversión
                int cod_producto = Integer.parseInt(Codigo_jTextField.getText());
                productoEditar.setIdProducto(cod_producto);
                productoEditar.setMarca(Marca_jTextField.getText());
                int stock_prod = Integer.parseInt(Precio_jTextField3.getText());
                productoEditar.setPrecio(stock_prod);
                int stock = Integer.parseInt(Stock_jTextField.getText());
                productoEditar.setStock(stock);
                productoEditar.setTipo(Stock_jTextField.getText());
            } catch (NumberFormatException n) {
                JOptionPane.showMessageDialog(this, "Gestión EnergyVera", "Asegurese que los campos númericos no contengan espacios o puntos", 2);
                return;
            } catch (NullPointerException e){
                JOptionPane.showMessageDialog(this, "Gestión EnergyVera", "Asegurese que los campos esten completos", 2);
                return;
            }
        //Detectar si estamos creando un nuevo cliente o editando uno actual para actualizarlo o guardarlo
        if (productoEditar != null) {
            serviceProd.actualizarProducto(productoEditar);
            JOptionPane.showMessageDialog(this, "Gestión EnergyVera", "factura " + productoEditar.getIdProducto()+ " editado exitosamente!", 2);
        } else {
            serviceProd.registrarProducto(productoEditar);
            JOptionPane.showMessageDialog(this, "Gestión EnergyVera", "factura " + productoEditar.getIdProducto()+ " añadido exitosamente!", 2);
        }
        FrmProductos factForm = new FrmProductos(serviceProd);
        factForm.setVisible(true);
        this.dispose();
    }//GEN-LAST:event_Guardar_jButtonActionPerformed


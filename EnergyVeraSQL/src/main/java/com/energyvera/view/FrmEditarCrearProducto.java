    public void inicializarVista() {
        if (productoEditar != null) {
            Titulo_JLabel.setText("Editar Producto");
            Codigo_jTextField.setText(String.valueOf(productoEditar.getIdProducto()));
            Marca_jTextField.setText(productoEditar.getMarca());
            Precio_jTextField3.setText(String.valueOf(productoEditar.getPrecio()));
            Stock_jTextField.setText(String.valueOf(productoEditar.getStock()));
            Tipo_jTextField.setText(String.valueOf(productoEditar.getTipo()));
            Guardar_jButton.setText("Guardar");
        }else{
            Titulo_JLabel.setText("Añadir Producto");
            Codigo_jTextField.setText("Número sin espacios ni letras");
            Marca_jTextField.setText("");
            Precio_jTextField3.setText("Número sin espacios ni letras");
            Stock_jTextField.setText("Número son espacios ni letras");
            Tipo_jTextField.setText("");
            Guardar_jButton.setText("Añadir");
        }
    }


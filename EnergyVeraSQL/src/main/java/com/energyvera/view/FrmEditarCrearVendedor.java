    public void inicializarVista() {
        if (vendedorEditar != null) {
            Titulo_JLabel.setText("Editar Factura");
            Codigo_jTextField.setText(String.valueOf(vendedorEditar.getIdVendedor()));
            Nombre_jTextField.setText(vendedorEditar.getNombre());
            Cargo_jTextField3.setText(String.valueOf(vendedorEditar.getCargo()));
            Guardar_jButton.setText("Guardar");
        }else{
            Titulo_JLabel.setText("Añadir Factura");
            Codigo_jTextField.setText("Número sin espacios ni letras");
            Nombre_jTextField.setText("");
            Cargo_jTextField3.setText("");
            Guardar_jButton.setText("Añadir");
        }
    }


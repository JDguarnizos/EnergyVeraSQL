    private void Guardar_jButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_Guardar_jButtonActionPerformed
        try {
                //Verificar que los campos no estén vacíos
            if (Codigo_jTextField.getText().isBlank()
                    || Nombre_jTextField.getText().isBlank()
                    || Cargo_jTextField3.getText().isBlank()
                    ) {
                throw new NullPointerException("");
            }
                //Intentar conversión
                int cod_factVenta = Integer.parseInt(Codigo_jTextField.getText());
                vendedorEditar.setIdVendedor(cod_factVenta);
                vendedorEditar.setNombre(Nombre_jTextField.getText());
                vendedorEditar.setCargo(Cargo_jTextField3.getText());
            } catch (NumberFormatException n) {//Código inútil pero bueh igual las excepciones no les hacen daño a nadie
                JOptionPane.showMessageDialog(this, "Gestión EnergyVera", "Asegurese que los campos númericos no contengan espacios o puntos", 2);
                return;
            } catch (NullPointerException e){
                JOptionPane.showMessageDialog(this, "Gestión EnergyVera", "Asegurese que los campos esten completos", 2);
                return;
            }
        //Detectar si estamos creando un nuevo cliente o editando uno actual para actualizarlo o guardarlo
        if (vendedorEditar != null) {
            serviceVendor.actualizarCargos(vendedorEditar); //Por que actualizar cargos?
            JOptionPane.showMessageDialog(this, "Gestión EnergyVera", "factura " + vendedorEditar.getNombre()+ " editado exitosamente!", 2);
        } else {
            serviceVendor.registrarVendedor(vendedorEditar);
            JOptionPane.showMessageDialog(this, "Gestión EnergyVera", "factura " + vendedorEditar.getNombre()+ " añadido exitosamente!", 2);
        }
        FrmVendedores factForm = new FrmVendedores(serviceVendor);
        factForm.setVisible(true);
        this.dispose();
    }//GEN-LAST:event_Guardar_jButtonActionPerformed


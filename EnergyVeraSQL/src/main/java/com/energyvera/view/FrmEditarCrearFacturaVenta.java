    public void inicializarVista() {
        if (facturaEditar != null) {
            Titulo_JLabel.setText("Editar Factura");
            Codigo_jTextField.setText(String.valueOf(facturaEditar.getIdCliente()));
            Fecha_jTextField.setText(facturaEditar.getFechaFacturaV().toString());
            IVA_jTextField3.setText(String.valueOf(facturaEditar.getIva()));
            CodCliente_jTextField.setText(String.valueOf(facturaEditar.getIdCliente()));
            CodVendor_jTextField.setText(String.valueOf(facturaEditar.getIdVendedor()));
            Guardar_jButton.setText("Guardar");
        }else{
            Titulo_JLabel.setText("Añadir Factura");
            Codigo_jTextField.setText("Número sin espacios ni letras");
            Fecha_jTextField.setText("Día/Mes/Año");
            IVA_jTextField3.setText("");
            CodCliente_jTextField.setText("Número sin espacios ni letras");
            CodVendor_jTextField.setText("Número sin espacios ni letras");
            Guardar_jButton.setText("Añadir");
        }
    }


    private void Guardar_jButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_Guardar_jButtonActionPerformed
        try {
                //Verificar que los campos no estén vacíos
            if (Codigo_jTextField.getText().isBlank()
                    || Fecha_jTextField.getText().isBlank()
                    || IVA_jTextField3.getText().isBlank()
                    || CodCliente_jTextField.getText().isBlank()
                    || CodVendor_jTextField.getText().isBlank()
                    ) {
                throw new NullPointerException("");
            }
                //Intentar conversión
                int cod_factVenta = Integer.parseInt(Codigo_jTextField.getText());
                facturaEditar.setIdFacturaVenta(cod_factVenta);
                Date fechaFactura = Date.valueOf(Fecha_jTextField.getText());
                facturaEditar.setFechaFacturaV(fechaFactura);
                int iva_factVenta = Integer.parseInt(IVA_jTextField3.getText());
                facturaEditar.setIva(iva_factVenta);
                int cod_cliente = Integer.parseInt(CodCliente_jTextField.getText());
                facturaEditar.setIdCliente(cod_cliente);
                int cod_vendor = Integer.parseInt(CodVendor_jTextField.getText());
                facturaEditar.setIdVendedor(cod_vendor);
            } catch (NumberFormatException n) {
                JOptionPane.showMessageDialog(this, "Gestión EnergyVera", "Asegurese que los campos númericos no contengan espacios o puntos", 2);
                return;
            } catch (NullPointerException e){
                JOptionPane.showMessageDialog(this, "Gestión EnergyVera", "Asegurese que los campos esten completos", 2);
                return;
            }
        //Detectar si estamos creando un nuevo cliente o editando uno actual para actualizarlo o guardarlo
        if (facturaEditar != null) {
            serviceFactVenta.actualizarFacturaVenta(facturaEditar);
            JOptionPane.showMessageDialog(this, "Gestión EnergyVera", "factura " + facturaEditar.getIdFacturaVenta()+ " editado exitosamente!", 2);
        } else {
            serviceFactVenta.registrarFacturaVenta(facturaEditar);
            JOptionPane.showMessageDialog(this, "Gestión EnergyVera", "factura " + facturaEditar.getIdFacturaVenta()+ " añadido exitosamente!", 2);
        }
        FrmFacturaVenta factForm = new FrmFacturaVenta(serviceFactVenta);
        factForm.setVisible(true);
        this.dispose();
    }//GEN-LAST:event_Guardar_jButtonActionPerformed


    private void Editar_jButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_Editar_jButtonActionPerformed
        try {
            if (VistaGarantias_jTable.getSelectedRow() == -1) {
                JOptionPane.showMessageDialog(this, "Gestión EnergyVera", "Debe seleccionar una factura o añadir una si no hay.", 2);
            } else {
                int seleccionado = VistaGarantias_jTable.getSelectedRow();
                garantia garantiaEditada = garService.buscarGarantiaPorId(Integer.parseInt(VistaGarantias_jTable.getValueAt(seleccionado, 0).toString()));

                FrmEditarCrearGarantia ventEditarGar = new FrmEditarCrearGarantia(garantiaEditada, garService);
                ventEditarGar.setVisible(true);
                this.dispose();
            }
        } catch (Exception NumberFormatException) {
            JOptionPane.showMessageDialog(this, "Gestión EnergyVera", "Ingrese un valor válido", 3);
        }
    }//GEN-LAST:event_Editar_jButtonActionPerformed

